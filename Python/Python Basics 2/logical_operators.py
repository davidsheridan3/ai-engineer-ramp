# Logical Operators
'''Operators: >, <, >=, <=, =, ==, !=, and,
 or, not '''
# Note: '=' is used to assign a variable, and '==' is used to compare values
print('a' > 'A') # True, how??
# because Python compares characters using their ASCII (or Unicode) numerical values. Lowercase letters have higher ASCII values than uppercase letters.
print(1 >= 0) # True
print(2 != 0) # True

# 'not' = the opposite. It is a keyword but also a function
print(not(True)) # False
